  /// Translates a given [key] into the current application language.
  /// If the translation does not exist in the active language, falls back to English,
  /// and if still missing, safely returns the [key] as-is.
  static String tr(String key, [String? langCode]) {
    final lang = langCode ?? LocaleController.instance.languageCode;
    final localized = _translations[lang]?[key];
    if (localized != null && localized.isNotEmpty) {
      return localized;
    }
    // Fallback to English
    final fallback = _translations['en']?[key];
    if (fallback != null && fallback.isNotEmpty) {
      return fallback;
    }
    // Return key safely
    return key;
  }
}

/// Convenience extension on [String] to allow `'Dashboard'.tr()` anywhere in the project.
extension StringLocalizationExtension on String {
  String tr([String? langCode]) => AppStrings.tr(this, langCode);
}
